-- custom-wayback · restore the D1 ledger from the Supabase mirror
-- ============================================================================
--
-- Run this when D1 is unusable — a lost database, or a free-plan row-write
-- ceiling that will not clear before the work matters. It materialises the mirror
-- into a `cw_restore` schema shaped exactly like D1, so the last step is a
-- mechanical `wrangler d1 execute` and not a mapping exercise.
--
--   -- 1. build the restore schema
--   psql "$SUPABASE_DB_URL" -f supabase/restore.sql
--
--   -- 2. check it
--   psql "$SUPABASE_DB_URL" -f supabase/verify.sql
--
--   -- 3. push it into D1 (per statement group; see docs/supabase-backup.md)
--
-- ## Why a separate schema rather than restoring in place
--
-- `cw_backup` is the live mirror: the Worker is still writing to it and the
-- cursors in `backup_state` still describe it. Rebuilding those tables in place
-- would fight the syncer and destroy the cursors that say what has been copied.
-- `cw_restore` is a materialised snapshot — cheap (it is a `CREATE TABLE AS` over
-- rows Postgres already stores) and safe to drop and rebuild.
--
-- ## Why statements and not COPY
--
-- D1 cannot restore from Postgres, and Cloudflare's import paths take JSON/SQL
-- rather than a wire-protocol dump. A plain-text SQL script is also the only
-- format a human can read before running it, which matters more here than
-- throughput: this is the step where a mistake is expensive.
--
-- ## Why the file is generated by the CLI rather than hand-written
--
-- `scripts/supabase-backup.mjs restore-sql` emits this against the real mirror,
-- including `content_digest` and `title` (added by migration 0004) and any column
-- a later migration adds. A hand-written list of columns would silently omit
-- exactly the newest ones — the ones least likely to have been re-derivable from
-- anywhere else. The statements below are the shape it produces.
--
-- ## Type conversions, stated once
--
--   * `bigint` → `INTEGER`: every timestamp, byte count and counter in this schema
--     fits comfortably in 32 bits (unix seconds until 2038, byte counts bounded by
--     the crawl budget). D1's INTEGER is 64-bit anyway, so this is a widening-free
--     downcast that cannot lose a value the tool can produce.
--   * `boolean` → `0`/`1`: SQLite has no boolean type. `disabled` and
--     `breaker_open` were written as integers, and the app reads them as
--     `r.disabled === 1` shapes throughout, so the restore must put integers back.
--   * `bytea` → base64 text: D1 has no binary literal, and its `TEXT` columns are
--     the only container available. `cdx_surveys.payload` is a gzip stream, so the
--     restored blob must be decoded back before it is usable — the note at the end
--     of this file is the honest statement of that one lossy step.
-- ============================================================================

create schema if not exists cw_restore;

-- Drop and rebuild. These are throwaway tables, and a half-restored schema that
-- looks complete is worse than none.
drop table if exists cw_restore.users cascade;
drop table if exists cw_restore.sessions cascade;
drop table if exists cw_restore.domains cascade;
drop table if exists cw_restore.ingests cascade;
drop table if exists cw_restore.snapshots cascade;
drop table if exists cw_restore.assets cascade;
drop table if exists cw_restore.link_resolutions cascade;
drop table if exists cw_restore.cdx_surveys cascade;
drop table if exists cw_restore.usage_ledger cascade;
drop table if exists cw_restore.throttle_events cascade;
drop table if exists cw_restore.rate_limits cascade;
drop table if exists cw_restore.search_docs cascade;
drop table if exists cw_restore.share_links cascade;
drop table if exists cw_restore.exports cascade;

-- ── Parents first, so the load order is the same as the read order ───────────

create table cw_restore.users as
select
  id                                   as id,
  email                                as email,
  password_hash                        as password_hash,
  created_at::integer                  as created_at,
  last_login_at::integer               as last_login_at,
  case when disabled then 1 else 0 end as disabled
from cw_backup.users;

create table cw_restore.sessions as
select
  id, user_id,
  issued_at::integer  as issued_at,
  expires_at::integer as expires_at,
  revoked_at::integer as revoked_at,
  user_agent, ip_hash
from cw_backup.sessions;

create table cw_restore.domains as
select
  id, user_id, domain, host_filter, budget_json, tracking_status,
  added_at::integer        as added_at,
  last_crawled_at::integer as last_crawled_at,
  coverage_json
from cw_backup.domains;

create table cw_restore.ingests as
select
  id, domain_id, month, status,
  pages_total::integer  as pages_total,
  pages_done::integer   as pages_done,
  assets_total::integer as assets_total,
  assets_done::integer  as assets_done,
  bytes_stored::integer as bytes_stored,
  budget_json,
  ia_429_count::integer as ia_429_count,
  error_message,
  started_at::integer   as started_at,
  finished_at::integer  as finished_at,
  queue_msg_id, stage,
  cursor::integer       as cursor,
  pages_json, assets_json,
  asset_cursor::integer as asset_cursor,
  degraded_reason, day_index_json,
  lease_until::integer  as lease_until,
  attempts::integer     as attempts,
  stage_attempts::integer as stage_attempts,
  consecutive_429::integer as consecutive_429,
  breaker_open_until::integer as breaker_open_until,
  last_throttle_at::integer   as last_throttle_at
from cw_backup.ingests;

-- The one table whose loss cannot be worked around: which capture was chosen for
-- which URL on which day. Everything else here can be re-derived or re-fetched.
create table cw_restore.snapshots as
select
  id, ingest_id, domain, url, day, ts,
  status_code::integer as status_code,
  mime, digest,
  bytes::integer       as bytes,
  r2_key, page_id, resolved_day, resolved_ts,
  delta_days::integer  as delta_days,
  served_at::integer   as served_at,
  purged_at::integer   as purged_at,
  content_digest, title
from cw_backup.snapshots;

create table cw_restore.assets as
select
  hash, mime,
  bytes::integer         as bytes,
  r2_key,
  first_seen_at::integer as first_seen_at,
  ref_count::integer     as ref_count,
  r2_deleted_at::integer as r2_deleted_at
from cw_backup.assets;

create table cw_restore.link_resolutions as
select
  id, domain, day, from_url, to_url, kind, resolved_day, resolved_ts,
  delta_days::integer as delta_days
from cw_backup.link_resolutions;

-- `encode(…, 'base64')` because D1's TEXT is the only place these bytes can go.
-- The restore into D1 therefore has to be followed by a decode step; see the note
-- at the end of this file and `docs/supabase-backup.md` §"Restoring cdx_surveys".
create table cw_restore.cdx_surveys as
select
  id, domain, month, query_hash,
  encode(payload, 'base64') as payload,
  fetched_at::integer       as fetched_at
from cw_backup.cdx_surveys;

create table cw_restore.usage_ledger as
select
  id::integer          as id,
  domain, month, kind,
  value::integer       as value,
  recorded_at::integer as recorded_at
from cw_backup.usage_ledger;

create table cw_restore.throttle_events as
select
  id::integer          as id,
  domain, month, ingest_id, host,
  status::integer      as status,
  wait_ms::integer     as wait_ms,
  attempt::integer     as attempt,
  case when breaker_open then 1 else 0 end as breaker_open,
  kind,
  created_at::integer  as created_at
from cw_backup.throttle_events;

create table cw_restore.rate_limits as
select
  bucket,
  window_start::integer as window_start,
  count::integer        as count,
  updated_at::integer   as updated_at
from cw_backup.rate_limits;

-- Only restorable if the mirror's `search_docs` was populated. The page *text*
-- that FTS5 indexes lives in the D1 virtual table, which is not mirrored — see
-- `packages/shared/src/backup.ts`. A restore therefore has to re-index from R2
-- (`POST /v1/search/reindex`) before cross-domain search works again.
create table cw_restore.search_docs as
select
  snapshot_id, domain, url, day, title,
  bytes::integer      as bytes,
  indexed_at::integer as indexed_at
from cw_backup.search_docs;

create table cw_restore.share_links as
select
  id, user_id, token_hash, domain, month, day, url, label,
  created_at::integer     as created_at,
  expires_at::integer     as expires_at,
  revoked_at::integer     as revoked_at,
  view_count::integer     as view_count,
  last_viewed_at::integer as last_viewed_at
from cw_backup.share_links;

create table cw_restore.exports as
select
  id, user_id, domain, month, r2_key,
  bytes::integer       as bytes,
  pages::integer       as pages,
  assets::integer      as assets,
  missing::integer     as missing,
  status, error_message,
  created_at::integer  as created_at,
  finished_at::integer as finished_at
from cw_backup.exports;

-- ── What is NOT restored ────────────────────────────────────────────────────
--
--   * **R2 page and asset bytes.** Deliberately: the post-serve purge deletes them
--     after `PURGE_GRACE_SECONDS`, so this is by design rather than a gap. The
--     ledger says what existed and where; the viewer re-fetches from archive.org
--     `id_` on demand, which is the same path an un-crawled page already takes
--     (plan.md §6.3). `r2_key` values are restored so the viewer knows what it is
--     missing, and `purged_at` distinguishes "never stored" from "deleted".
--   * **`snapshot_fts`.** An FTS5 virtual table — a SQLite index, not data. It is
--     rebuilt from `search_docs` plus R2 by the re-index endpoint.
--   * **Cloudflare Queues in flight.** Messages reference ingest ids that will
--     exist again after the restore, and every stage is idempotent and resumes
--     from the cursor columns, which *are* restored, so re-driving a job is safe.
